/**
 * Пауза ВНУТРИ запроса, который кто-то ждёт (листание страниц, ожидание запрета биржи) — это
 * работа, и процесс обязан её дождаться. Снятый с удержания таймер (`unref`) давал процессу
 * тихо завершиться с кодом 0 посреди такой паузы, если в этот миг больше ничего не держало его
 * живым: бот на Bybit при старте листал ступени риска с паузой между страницами и исчезал без
 * единой ошибки (rubber, 18.09.2026, воспроизведено три раза из трёх).
 */
export function sleep(milliseconds: number): Promise<void> {
  return new Promise((resolve) => {
    setTimeout(resolve, milliseconds);
  });
}
